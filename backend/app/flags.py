# The regional indicator symbols start at U+1F1E6 for "A", so a two-letter code
# maps to two code points and the font draws the flag. No lookup table of literal
# emoji is needed, and an invalid code is caught by `flag_emoji` rather than
# silently rendering as letters.
_INDICATOR_BASE = 0x1F1E6


def flag_emoji(code: str) -> str:
    """The flag emoji for an ISO 3166-1 alpha-2 code, e.g. ``"NG"`` -> 🇳🇬."""
    if len(code) != 2 or not code.isalpha() or not code.isupper():
        raise ValueError(f"not an ISO 3166-1 alpha-2 code: {code!r}")
    return "".join(chr(_INDICATOR_BASE + ord(letter) - ord("A")) for letter in code)
